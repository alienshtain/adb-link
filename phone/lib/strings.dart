/// Tiny translation helper: write the English text, get Arabic when the phone is set to Arabic.
bool get isArabic {
  final choice = AppStyle.I.language;
  if (choice == 'ar') return true;
  if (choice == 'en') return false;
  return ui.PlatformDispatcher.instance.locale.languageCode == 'ar';
}

